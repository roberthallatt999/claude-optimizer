#!/usr/bin/env bash
#
# install-global-guard.sh
# Guard every Claude Code session on this machine, not only projects ai-config deployed to.
#
# ai-config puts the safety policy (deny rules + the safety-guard.sh hook) into each project's
# .claude/settings.local.json. A session anywhere else (a new side-project folder, ~/Downloads,
# this repo) had none of it, while the user-level settings pre-approved broad reads. This:
#
#   1. links ~/.claude/hooks/safety-guard.sh to this repo's guard (a git pull updates it), and
#      writes ~/.claude/hooks/protected-paths.conf from the shared [deny] tier;
#   2. registers it as a PreToolUse hook in ~/.claude/settings.json with
#      AI_CONFIG_GUARD_SCOPE=global, so it stands aside in a project that runs its own guard;
#   3. adds the shared secret-file deny rules to the user-level permissions.deny;
#   4. removes user-level allow rules broad enough to defeat the policy: reading the whole home
#      folder, and gh auth/repo/api wildcards, workflow runs and repo visibility changes.
#
# ~/.claude/settings.json is backed up to ~/.claude/backups/ before any change.
#
# Usage:
#   scripts/install-global-guard.sh            # install or update (idempotent)
#   scripts/install-global-guard.sh --check    # report; exit 1 if not installed
#   scripts/install-global-guard.sh --remove   # unregister the hook and the deny rules it added
#
# AI_CONFIG_CLAUDE_DIR overrides ~/.claude (tests).

# Messages name ~/.claude literally, for the reader; nothing here relies on tilde expansion.
# shellcheck disable=SC2088
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CLAUDE_DIR="${AI_CONFIG_CLAUDE_DIR:-$HOME/.claude}"
SETTINGS="$CLAUDE_DIR/settings.json"
HOOK_DIR="$CLAUDE_DIR/hooks"
GUARD_SRC="$ROOT/projects/common/hooks/safety-guard.sh"
POLICY="$ROOT/projects/common/security.settings.local.json"
PROTECTED="$ROOT/projects/common/protected-paths.conf"
MARK="AI_CONFIG_GUARD_SCOPE=global"
COMMAND="$MARK \"\$HOME\"/.claude/hooks/safety-guard.sh"
MATCHER="$(jq -r '.hooks.PreToolUse[0].matcher' "$POLICY")"

GREEN=$'\033[0;32m'; YELLOW=$'\033[1;33m'; NC=$'\033[0m'
ok()   { echo -e "  ${GREEN}✓${NC} $*"; }
note() { echo -e "  ${YELLOW}○${NC} $*"; }

command -v jq >/dev/null 2>&1 || { echo "install-global-guard: jq is required" >&2; exit 1; }

# Broad user-level allows that would auto-approve what the policy exists to stop. The guard's
# deny/ask still apply on top, but an allow this wide also skips every prompt the guard
# doesn't make, so they go. Exact one-off approvals (gh run view 123 …) stay.
RISKY_ALLOW='^Read\((//(Users|home)/[^/]+|~)/\*\*\)$|^Bash\(gh (auth|repo|api|secret|variable):\*\)$|^Bash\(gh (workflow run|repo (edit|delete|create|rename|archive))[ :)]|^Bash\(git push[ :)]|^Bash\(security find-(generic|internet)-password'

backup_settings() {
  mkdir -p "$CLAUDE_DIR/backups"
  [[ -f "$SETTINGS" ]] && cp -p "$SETTINGS" "$CLAUDE_DIR/backups/settings-$(date +%Y%m%d-%H%M%S).json"
  return 0
}

write_settings() {   # <new json>
  local current="{}"
  [[ -f "$SETTINGS" ]] && current="$(cat "$SETTINGS")"
  if [[ "$(jq -S -c . <<< "$current")" == "$(jq -S -c . <<< "$1")" ]]; then return 1; fi
  backup_settings
  mkdir -p "$CLAUDE_DIR"
  printf '%s\n' "$1" > "$SETTINGS.tmp" && mv "$SETTINGS.tmp" "$SETTINGS"
}

registered() { [[ -f "$SETTINGS" ]] && jq -e --arg m "$MARK" '[.hooks.PreToolUse[]?.hooks[]?.command | strings | contains($m)] | any' "$SETTINGS" >/dev/null 2>&1; }

install() {
  local base removed updated
  mkdir -p "$HOOK_DIR"
  if [[ -e "$HOOK_DIR/safety-guard.sh" && ! -L "$HOOK_DIR/safety-guard.sh" ]]; then
    mv "$HOOK_DIR/safety-guard.sh" "$CLAUDE_DIR/backups/safety-guard.sh.$(date +%Y%m%d-%H%M%S)" 2>/dev/null \
      || { mkdir -p "$CLAUDE_DIR/backups"; mv "$HOOK_DIR/safety-guard.sh" "$CLAUDE_DIR/backups/"; }
  fi
  if [[ "$(readlink "$HOOK_DIR/safety-guard.sh" 2>/dev/null)" != "$GUARD_SRC" ]]; then
    ln -sfn "$GUARD_SRC" "$HOOK_DIR/safety-guard.sh"
    ok "Linked ~/.claude/hooks/safety-guard.sh → this repo's guard"
  fi
  local conf; conf="$(mktemp)"
  { echo "# Generated by claude-optimizer scripts/install-global-guard.sh from projects/common/protected-paths.conf [deny]."
    echo "# Used by the global guard outside ai-config projects. Regenerated on every install.sh run."
    awk '/^\[deny\]/{d=1;next} /^\[/{d=0} d && !/^[[:space:]]*#/ && NF' "$PROTECTED"; } > "$conf"
  if ! cmp -s "$conf" "$HOOK_DIR/protected-paths.conf" 2>/dev/null; then
    mv "$conf" "$HOOK_DIR/protected-paths.conf"; ok "Wrote ~/.claude/hooks/protected-paths.conf"
  else
    rm -f "$conf"
  fi

  base="{}"; [[ -f "$SETTINGS" ]] && base="$(cat "$SETTINGS")"
  jq empty <<< "$base" 2>/dev/null || { echo "install-global-guard: $SETTINGS is not valid JSON; nothing changed" >&2; exit 1; }
  removed="$(jq -r --arg re "$RISKY_ALLOW" '.permissions.allow[]? | select(test($re))' <<< "$base")"
  updated="$(jq --arg m "$MARK" --arg cmd "$COMMAND" --arg matcher "$MATCHER" --arg re "$RISKY_ALLOW" \
                --slurpfile pol "$POLICY" '
      .permissions.deny = ((.permissions.deny // []) + ($pol[0].permissions.deny // []) | unique)
    | (if .permissions.allow then .permissions.allow |= map(select(test($re) | not)) else . end)
    | .hooks.PreToolUse = (
        ((.hooks.PreToolUse // []) | map(.hooks |= map(select((.command // "") | contains($m) | not)))
                                   | map(select((.hooks | length) > 0)))
        + [{matcher: $matcher, hooks: [{type: "command", command: $cmd, timeout: 10}]}])' <<< "$base")"
  if write_settings "$updated"; then
    ok "~/.claude/settings.json: safety guard registered for every session, secret-file deny rules added"
    if [[ -n "$removed" ]]; then
      ok "Removed broad allow rules (backup in ~/.claude/backups/):"
      while IFS= read -r r; do echo "      $r"; done <<< "$removed"
    fi
  else
    ok "Global safety guard already installed"
  fi
}

check() {
  local rc=0
  if registered; then ok "Global guard registered in ~/.claude/settings.json"; else note "Global guard not registered"; rc=1; fi
  if [[ -e "$HOOK_DIR/safety-guard.sh" ]]; then ok "~/.claude/hooks/safety-guard.sh present"; else note "~/.claude/hooks/safety-guard.sh missing"; rc=1; fi
  local risky; risky="$( [[ -f "$SETTINGS" ]] && jq -r --arg re "$RISKY_ALLOW" '.permissions.allow[]? | select(test($re))' "$SETTINGS")"
  if [[ -n "$risky" ]]; then note "Broad allow rules present: $(tr '\n' ' ' <<< "$risky")"; rc=1; fi
  return $rc
}

remove() {
  local base updated
  [[ -f "$SETTINGS" ]] || { note "No ~/.claude/settings.json"; return 0; }
  base="$(cat "$SETTINGS")"
  updated="$(jq --arg m "$MARK" --slurpfile pol "$POLICY" '
      .permissions.deny = ((.permissions.deny // []) - ($pol[0].permissions.deny // []))
    | .hooks.PreToolUse = ((.hooks.PreToolUse // []) | map(.hooks |= map(select((.command // "") | contains($m) | not)))
                                                     | map(select((.hooks | length) > 0)))
    | if (.hooks.PreToolUse | length) == 0 then del(.hooks.PreToolUse) else . end
    | if (.hooks | length) == 0 then del(.hooks) else . end' <<< "$base")"
  write_settings "$updated" && ok "Global guard unregistered and its deny rules removed (backup in ~/.claude/backups/)"
  [[ -L "$HOOK_DIR/safety-guard.sh" ]] && rm -f "$HOOK_DIR/safety-guard.sh" && ok "Removed ~/.claude/hooks/safety-guard.sh link"
  rm -f "$HOOK_DIR/protected-paths.conf"
  return 0
}

case "${1:-}" in
  "")       install ;;
  --check)  check ;;
  --remove) remove ;;
  *) sed -n '/^# Usage:/,/^# AI_CONFIG/p' "$0" | sed 's/^# \{0,1\}//' >&2; exit 2 ;;
esac
